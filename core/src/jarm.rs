#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Order {
    Forward,
    Reverse,
    TopHalf,
    BottomHalf,
    MiddleOut,
}
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Version {
    Tls11,
    Tls12,
    Tls13,
}
/// What the supported_versions extension offers: nothing (no extension), TLS 1.0 to 1.2
/// ("1.2_SUPPORT") or TLS 1.0 to 1.3.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Support {
    None,
    Tls12,
    Tls13,
}

/// One of the ten probes (the arrays at the top of `main()` in `jarm.py`).
#[derive(Clone, Copy, Debug)]
pub struct Probe {
    pub name: &'static str,
    version: Version,
    /// Offer the TLS 1.3 suites too ("ALL") or only the older ones ("NO1.3").
    all_ciphers: bool,
    order: Order,
    grease: bool,
    rare_alpn: bool,
    support: Support,
    /// The reference's "extension order" REVERSE: it reverses the ALPN list and the
    /// supported_versions list (not the extensions themselves).
    reverse_lists: bool,
}

#[allow(clippy::too_many_arguments)]
const fn probe(
    name: &'static str,
    version: Version,
    all_ciphers: bool,
    order: Order,
    grease: bool,
    rare_alpn: bool,
    support: Support,
    reverse_lists: bool,
) -> Probe {
    Probe {
        name,
        version,
        all_ciphers,
        order,
        grease,
        rare_alpn,
        support,
        reverse_lists,
    }
}

