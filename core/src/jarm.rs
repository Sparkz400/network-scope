//! JARM active TLS server fingerprint (opt-in, never in Safe Mode).
//!
//! JARM (Salesforce, BSD-3-Clause, <https://github.com/salesforce/jarm>) sends ten differently
//! shaped TLS ClientHellos to one port and condenses the ServerHellos into a 62 character hash:
//! per probe the selected cipher (2 hex characters, its index in the reference's sorted cipher
//! table) and the selected version (1 letter), 30 characters in all, then the first 32 hex
//! characters of the SHA-256 over the ALPN and extension lists of all ten replies. All replies
//! missing gives 62 zeros.
//!
//! Verified against the reference implementation: the hellos, the reading of the replies and the
//! hash are a transcription of `jarm.py` (commit e00ad79, 2026-08-13), and the unit tests compare
//! them byte for byte with vectors that `lab/jarm_reference.py` generated by running the reference
//! code (`jarm_reference_hellos.txt`, `jarm_reference_replies.txt`). `lab/jarm_compare.py` runs
//! `jarm.py` and this scanner against the same live TLS servers; the results are in
//! docs/src/detection.md. Differences that remain on purpose:
//!
//! - the random bytes (client random, session id, key share) and the GREASE values come from
//!   this program's own generator, as the reference draws them at random too; servers ignore them;
//! - the connect and read timeout is the scan's port timeout (0.5 to 5 seconds), not the
//!   reference's 20 seconds;
//! - a truncated reply is read as the reference reads it where that is well defined (the reference
//!   then fails in Python exceptions or produces a garbage value; either way this reads it the
//!   same or as no answer);
//! - like the reference, a timeout on any probe ends the fingerprint with 62 zeros (and no
//!   further hello is sent); a refused, reset or closed connection only empties that probe.
//!
//! The ClientHello builder uses the raw TLS bytes of its own (not rustls) so that it can offer
//! SSL/TLS versions and suites that rustls refuses.
//!
//! Sending: ten short connections per port, each through the scan's rate gate, only to ports
//! that already identified as TLS and are neither industrial nor printer ports. The scanner
//! only enables it outside Safe Mode and with `--jarm`.
use crate::{core::Gate, fingerprint, sendlog::PacketKind, tls};
use std::{net::IpAddr, time::Duration};
use tokio::{
    io::{AsyncReadExt, AsyncWriteExt},
    net::TcpStream,
    time::timeout,
};

