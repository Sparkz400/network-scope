/// ALPN protocols, weakest to strongest; the "rare" list drops `http/1.1` and `h2`.
const ALPN_COMMON: [&[u8]; 9] = [
    b"http/0.9",
    b"http/1.0",
    b"http/1.1",
    b"spdy/1",
    b"spdy/2",
    b"spdy/3",
    b"h2",
    b"h2c",
    b"hq",
];
const ALPN_RARE: [&[u8]; 7] = [
    b"http/0.9",
    b"http/1.0",
    b"spdy/1",
    b"spdy/2",
    b"spdy/3",
    b"h2c",
    b"hq",
];

/// The random parts of a ClientHello: the reference takes them from the operating system's
/// random source and a random GREASE value for each use. Fixed in the tests.
pub struct Nonces {
    pub random: [u8; 32],
    pub session: [u8; 32],
    pub key_share: [u8; 32],
    /// GREASE values for the cipher list, the first extension, the key share and the
    /// supported_versions list, in that order (each of the form 0x?a?a).
    pub grease: [u16; 4],
}

impl Nonces {
    fn fresh() -> Nonces {
        let g = tls::random32();
        let grease = |b: u8| {
            let nibble = u16::from(b >> 4);
            (nibble << 12) | 0x0a00 | (nibble << 4) | 0x000a
        };
        Nonces {
            random: tls::random32(),
            session: tls::random32(),
            key_share: tls::random32(),
            grease: [grease(g[0]), grease(g[1]), grease(g[2]), grease(g[3])],
        }
    }
}

/// The reference's `cipher_mung`: reorders a list (also used for the ALPN and version lists).
fn mung<T: Copy>(items: &[T], order: Order) -> Vec<T> {
    let n = items.len();
    match order {
        Order::Forward => items.to_vec(),
        Order::Reverse => items.iter().rev().copied().collect(),
        Order::BottomHalf => items[(n / 2 + n % 2).min(n)..].to_vec(),
        Order::TopHalf => {
            // The middle element first when the count is odd, then the bottom half of the
            // reversed list.
            let mut out = vec![];
            if n % 2 == 1 {
                out.push(items[n / 2]);
            }
            out.extend(mung(&mung(items, Order::Reverse), Order::BottomHalf));
            out
        }
        Order::MiddleOut => {
            let mid = n / 2;
            let mut out = vec![];
            if n % 2 == 1 {
                out.push(items[mid]);
                for i in 1..=mid {
                    out.push(items[mid + i]);
                    out.push(items[mid - i]);
                }
            } else {
                for i in 1..=mid {
                    out.push(items[mid - 1 + i]);
                    out.push(items[mid - i]);
                }
            }
            out
        }
    }
}

fn ciphers(p: &Probe, grease: u16) -> Vec<u16> {
    let base: Vec<u16> = ALL
        .iter()
        .copied()
        .filter(|c| p.all_ciphers || c >> 8 != 0x13)
        .collect();
    let mut out = mung(&base, p.order);
    if p.grease {
        out.insert(0, grease);
    }
    out
}

fn alpn_extension(p: &Probe) -> Vec<u8> {
    let list: &[&[u8]] = if p.rare_alpn {
        &ALPN_RARE
    } else {
        &ALPN_COMMON
    };
    let list = mung(
        list,
        if p.reverse_lists {
            Order::Reverse
        } else {
            Order::Forward
        },
    );
    let mut protos = vec![];
    for a in list {
        protos.push(a.len() as u8);
        protos.extend(a);
    }
    let mut out = vec![0x00, 0x10];
    out.extend(((protos.len() + 2) as u16).to_be_bytes());
    out.extend((protos.len() as u16).to_be_bytes());
    out.extend(protos);
    out
}

fn key_share_extension(p: &Probe, n: &Nonces) -> Vec<u8> {
    let mut share = vec![];
    if p.grease {
        share.extend(n.grease[2].to_be_bytes());
        share.extend([0x00, 0x01, 0x00]);
    }
    share.extend([0x00, 0x1d, 0x00, 0x20]);
    share.extend(n.key_share);
    let mut out = vec![0x00, 0x33];
    out.extend(((share.len() + 2) as u16).to_be_bytes());
    out.extend((share.len() as u16).to_be_bytes());
    out.extend(share);
    out
}

fn supported_versions_extension(p: &Probe, n: &Nonces) -> Vec<u8> {
    let list: &[[u8; 2]] = if p.support == Support::Tls12 {
        &[[3, 1], [3, 2], [3, 3]]
    } else {
        &[[3, 1], [3, 2], [3, 3], [3, 4]]
    };
    let list = mung(
        list,
        if p.reverse_lists {
            Order::Reverse
        } else {
            Order::Forward
        },
    );
    let mut versions = vec![];
    if p.grease {
        versions.extend(n.grease[3].to_be_bytes());
    }
    for v in list {
        versions.extend(v);
    }
    let mut out = vec![0x00, 0x2b];
    out.extend(((versions.len() + 1) as u16).to_be_bytes());
    out.push(versions.len() as u8);
    out.extend(versions);
    out
}

fn extensions(p: &Probe, host: &str, n: &Nonces) -> Vec<u8> {
    let mut e = vec![];
    if p.grease {
        e.extend(n.grease[1].to_be_bytes());
        e.extend([0x00, 0x00]);
    }
    // Server name.
    let name = host.as_bytes();
    e.extend([0x00, 0x00]);
    e.extend(((name.len() + 5) as u16).to_be_bytes());
    e.extend(((name.len() + 3) as u16).to_be_bytes());
    e.push(0);
    e.extend((name.len() as u16).to_be_bytes());
    e.extend(name);
    e.extend([0x00, 0x17, 0x00, 0x00]); // extended master secret
    e.extend([0x00, 0x01, 0x00, 0x01, 0x01]); // max fragment length
    e.extend([0xff, 0x01, 0x00, 0x01, 0x00]); // renegotiation info
    e.extend([
        0x00, 0x0a, 0x00, 0x0a, 0x00, 0x08, 0x00, 0x1d, 0x00, 0x17, 0x00, 0x18, 0x00, 0x19,
    ]); // supported groups: x25519, secp256r1, secp384r1, secp521r1
    e.extend([0x00, 0x0b, 0x00, 0x02, 0x01, 0x00]); // EC point formats
    e.extend([0x00, 0x23, 0x00, 0x00]); // session ticket
    e.extend(alpn_extension(p));
    e.extend([
        0x00, 0x0d, 0x00, 0x14, 0x00, 0x12, 0x04, 0x03, 0x08, 0x04, 0x04, 0x01, 0x05, 0x03, 0x08,
        0x05, 0x05, 0x01, 0x08, 0x06, 0x06, 0x01, 0x02, 0x01,
    ]); // signature algorithms
    e.extend(key_share_extension(p, n));
    e.extend([0x00, 0x2d, 0x00, 0x02, 0x01, 0x01]); // PSK key exchange modes
    if p.version == Version::Tls13 || p.support == Support::Tls12 {
        e.extend(supported_versions_extension(p, n));
    }
    e
}

/// The ClientHello record of a probe, as `packet_building` of `jarm.py` builds it. `host` goes
/// into the server name extension (the reference uses the address or name it was given).
pub fn client_hello(p: &Probe, host: &str, n: &Nonces) -> Vec<u8> {
    let (record_version, hello_version): ([u8; 2], [u8; 2]) = match p.version {
        Version::Tls13 => ([3, 1], [3, 3]),
        Version::Tls12 => ([3, 3], [3, 3]),
        Version::Tls11 => ([3, 2], [3, 2]),
    };
    let suites = ciphers(p, n.grease[0]);
    let mut body = hello_version.to_vec();
    body.extend(n.random);
    body.push(32);
    body.extend(n.session);
    body.extend(((suites.len() * 2) as u16).to_be_bytes());
    for s in &suites {
        body.extend(s.to_be_bytes());
    }
    body.extend([1, 0]); // one compression method: null
    let exts = extensions(p, host, n);
    body.extend((exts.len() as u16).to_be_bytes());
    body.extend(exts);

    let mut handshake = vec![1, 0];
    handshake.extend((body.len() as u16).to_be_bytes());
    handshake.extend(body);
    let mut record = vec![22];
    record.extend(record_version);
    record.extend((handshake.len() as u16).to_be_bytes());
    record.extend(handshake);
    record
}

/// What a ServerHello tells JARM, as `read_packet` of `jarm.py` extracts it. The fields keep the
/// raw bytes: a truncated reply gives the reference short values, and so it does here.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Response {
    pub cipher: Vec<u8>,
    pub version: Vec<u8>,
    /// Selected ALPN protocol, empty when none.
    pub alpn: String,
    /// Extension types in the order the server sent them.
    pub extensions: Vec<Vec<u8>>,
}

/// Python's `data[a:b]` for non-negative bounds: clamped, never out of range.
fn slice(data: &[u8], a: usize, b: usize) -> &[u8] {
    let a = a.min(data.len());
    let b = b.clamp(a, data.len());
    &data[a..b]
}

/// `int(hex(data), 16)` of a slice: big endian, and nothing at all for an empty slice.
fn be_int(data: &[u8]) -> Option<usize> {
    (!data.is_empty()).then(|| data.iter().fold(0usize, |v, b| (v << 8) | usize::from(*b)))
}

/// Reads a ServerHello from the first bytes a server answered with. `None` for an alert, for
/// anything that is not a ServerHello and where the reference gives up (`|||`); never panics
/// (fuzzed).
pub fn parse_response(data: &[u8]) -> Option<Response> {
    if *data.first()? != 22 || *data.get(5)? != 2 {
        return None;
    }
    let record_len = be_int(slice(data, 3, 5))?;
    let counter = usize::from(*data.get(43)?);
    let cipher = slice(data, counter + 44, counter + 46).to_vec();
    let version = slice(data, 9, 11).to_vec();
    let (alpn, extensions) = extension_info(data, counter, record_len)?;
    Some(Response {
        cipher,
        version,
        alpn,
        extensions,
    })
}

/// The reference's `extract_extension_info`: the ALPN protocol and the extension types, an
/// empty result where it returns `|`, and `None` where one of its Python exceptions ends the
/// whole reading.
fn extension_info(
    data: &[u8],
    counter: usize,
    record_len: usize,
) -> Option<(String, Vec<Vec<u8>>)> {
    let nothing = Some((String::new(), vec![]));
    // No extensions field: the next handshake message (a Certificate, type 11) follows.
    match data.get(counter + 47) {
        None | Some(11) => return nothing,
        _ => {}
    }
    if slice(data, counter + 50, counter + 53) == [0x0e, 0xac, 0x0b]
        || slice(data, 82, 85) == [0x0f, 0xf0, 0x0b]
        || counter + 42 >= record_len
    {
        return nothing;
    }
    let mut count = 49 + counter;
    let length = be_int(slice(data, counter + 47, counter + 49))?;
    let maximum = length + count - 1;
    let mut types: Vec<&[u8]> = vec![];
    // None: a zero-length extension (a text "", which the reference cannot decode as ALPN).
    let mut values: Vec<Option<&[u8]>> = vec![];
    while count < maximum {
        types.push(slice(data, count, count + 2));
        let ext_length = be_int(slice(data, count + 2, count + 4))?;
        if ext_length == 0 {
            count += 4;
            values.push(None);
        } else {
            values.push(Some(slice(data, count + 4, count + 4 + ext_length)));
            count += ext_length + 4;
        }
    }
    let alpn = match types.iter().position(|t| *t == [0x00, 0x10]) {
        None => String::new(),
        Some(i) => {
            let value = values[i]?;
            String::from_utf8(slice(value, 3, value.len()).to_vec()).ok()?
        }
    };
    Some((alpn, types.into_iter().map(<[u8]>::to_vec).collect()))
}

fn hex(bytes: &[u8]) -> String {
    fingerprint::hex(bytes)
}

/// The per-probe line the hash is built from: `cipher|version|alpn|ext-ext` (`|||` for no
/// ServerHello), as in the reference tool's raw output.
pub fn response_line(r: Option<&Response>) -> String {
    match r {
        None => "|||".into(),
        Some(r) => format!(
            "{}|{}|{}|{}",
            hex(&r.cipher),
            hex(&r.version),
            r.alpn,
            r.extensions
                .iter()
                .map(|e| hex(e))
                .collect::<Vec<_>>()
                .join("-")
        ),
    }
}

/// The two hex characters of a cipher in the hash: its 1-based index in [`CIPHER_TABLE`].
fn cipher_byte(line: &str) -> String {
    let cipher = line.split('|').next().unwrap_or("");
    if cipher.is_empty() {
        return "00".into();
    }
    let index = CIPHER_TABLE
        .iter()
        .position(|c| format!("{c:04x}") == cipher)
        .unwrap_or(CIPHER_TABLE.len())
        + 1;
    format!("{index:02x}")
}
/// The letter of the selected version: `a` for SSL 3.0, `b` TLS 1.0, `c` 1.1, `d` 1.2, `e` 1.3,
/// from the last hex digit of the version field; `0` without a ServerHello.
fn version_byte(line: &str) -> char {
    let version = line.split('|').nth(1).unwrap_or("");
    match version.chars().nth(3).and_then(|c| c.to_digit(16)) {
        Some(d) => ['a', 'b', 'c', 'd', 'e', 'f'][usize::try_from(d).unwrap_or(5).min(5)],
        None => '0',
    }
}

/// The 62 character fingerprint from the ten per-probe lines.
pub fn hash(lines: &[String]) -> String {
    if lines.iter().all(|l| l == "|||") {
        return "0".repeat(62);
    }
    let mut fuzzy = String::new();
    let mut tail = String::new();
    for l in lines {
        fuzzy.push_str(&cipher_byte(l));
        fuzzy.push(version_byte(l));
        let mut parts = l.split('|').skip(2);
        tail.push_str(parts.next().unwrap_or(""));
        tail.push_str(parts.next().unwrap_or(""));
    }
    let digest = fingerprint::hex(&fingerprint::sha256(tail.as_bytes()));
    format!("{fuzzy}{}", &digest[..32])
}

/// Same-shaped check for tests and the identity value: 62 lower-case hex characters.
pub fn is_jarm(s: &str) -> bool {
    s.len() == 62
        && s.bytes()
            .all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase())
}

/// JARM runs only when asked for (`--jarm`), after service detection found the TLS ports, and
/// never in Safe Mode.
pub fn enabled(s: &crate::scan::Settings) -> bool {
    s.jarm && s.services && !s.safe
}

/// The detail the ten hellos are recorded under in the sent log, and listed under in the dry
/// run (`plan::host`).
pub const DETAIL: &str = "JARM fingerprint hello";

/// Ports JARM never touches: industrial and printer ports (the generic probes' deny list).
pub fn allowed_port(port: u16) -> bool {
    !crate::service::is_ot_udp_port(port)
}

/// What one probe got.
enum Reply {
    /// Connect or read timed out: the reference ends the whole fingerprint here with zeros.
    Timeout,
    /// Connection refused, reset or closed without data.
    Nothing,
    Data(Vec<u8>),
}

/// Fingerprints one TLS port with up to ten connections, each through the rate gate. `None`
/// when the port is on the deny list.
pub async fn fingerprint(ip: IpAddr, port: u16, limit: Duration, gate: &Gate) -> Option<String> {
    if !allowed_port(port) {
        return None;
    }
    let host = ip.to_string();
    let mut lines = vec![];
    for p in &PROBES {
        gate.wait_for(PacketKind::TlsClientHello, DETAIL).await;
        match send(ip, port, &client_hello(p, &host, &Nonces::fresh()), limit).await {
            Reply::Timeout => return Some("0".repeat(62)),
            Reply::Nothing => lines.push(response_line(None)),
            Reply::Data(d) => lines.push(response_line(parse_response(&d).as_ref())),
        }
    }
    Some(hash(&lines))
}

async fn send(ip: IpAddr, port: u16, hello: &[u8], limit: Duration) -> Reply {
    let Ok(connected) = timeout(limit, TcpStream::connect((ip, port))).await else {
        return Reply::Timeout;
    };
    let Ok(mut stream) = connected else {
        return Reply::Nothing;
    };
    if stream.write_all(hello).await.is_err() {
        return Reply::Nothing;
    }
    let mut buf = vec![0u8; 1484];
    match timeout(limit, stream.read(&mut buf)).await {
        Err(_) => Reply::Timeout,
        Ok(Ok(n)) if n > 0 => {
            buf.truncate(n);
            Reply::Data(buf)
        }
        Ok(_) => Reply::Nothing,
    }
}

