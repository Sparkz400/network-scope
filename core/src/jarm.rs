    #[tokio::test]
    async fn a_tls_server_gets_ten_hellos_and_a_stable_hash() {
        use tokio::net::TcpListener;
        let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let port = listener.local_addr().unwrap().port();
        let seen = std::sync::Arc::new(std::sync::atomic::AtomicUsize::new(0));
        let counter = seen.clone();
        tokio::spawn(async move {
            loop {
                let Ok((mut s, _)) = listener.accept().await else {
                    return;
                };
                counter.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
                let mut buf = [0u8; 2048];
                let _ = s.read(&mut buf).await;
                let _ = s
                    .write_all(&server_hello(0xc030, Some("http/1.1"), 0x0303))
                    .await;
            }
        });
        let gate = Gate::unlimited();
        let ip: IpAddr = "127.0.0.1".parse().unwrap();
        let a = fingerprint(ip, port, Duration::from_secs(2), &gate)
            .await
            .unwrap();
        let b = fingerprint(ip, port, Duration::from_secs(2), &gate)
            .await
            .unwrap();
        assert!(is_jarm(&a) && a == b, "{a} {b}");
        assert_ne!(a, "0".repeat(62));
        assert_eq!(seen.load(std::sync::atomic::Ordering::SeqCst), 20);
        // Every hello is recorded in the sent log (ten per fingerprint), and the dry run plan
        // lists what is recorded.
        let sent = gate.log().snapshot();
        assert_eq!(sent.len(), 1, "{sent:?}");
        assert_eq!(
            (sent[0].kind, sent[0].detail.as_str(), sent[0].count),
            (PacketKind::TlsClientHello, DETAIL, 20)
        );
        let s = crate::scan::Settings {
            jarm: true,
            services: true,
            safe: false,
            ..Default::default()
        };
        let plan = crate::plan::host(ip, &[443], &[], &s, None);
        assert!(
            plan.keys()
                .contains(&(PacketKind::TlsClientHello, DETAIL.to_string()))
        );
        let safe = crate::scan::Settings { safe: true, ..s };
        let plan = crate::plan::host(ip, &[443], &[], &safe, None);
        assert!(
            !plan
                .keys()
                .contains(&(PacketKind::TlsClientHello, DETAIL.to_string()))
        );
        // A port that refuses the connection: all probes empty, 62 zeros.
        let closed = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let cport = closed.local_addr().unwrap().port();
        drop(closed);
        let none = fingerprint(ip, cport, Duration::from_millis(300), &gate)
            .await
            .unwrap();
        assert_eq!(none, "0".repeat(62));
        // Deny list.
        assert_eq!(
            fingerprint(ip, 502, Duration::from_millis(100), &gate).await,
            None
        );
    }

