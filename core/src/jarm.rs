    fn unhex(s: &str) -> Vec<u8> {
        (0..s.len() / 2)
            .map(|i| u8::from_str_radix(&s[2 * i..2 * i + 2], 16).unwrap())
            .collect()
    }

    /// The fixed randomness the reference vectors were generated with.
    fn fixed() -> Nonces {
        Nonces {
            random: [1; 32],
            session: [2; 32],
            key_share: [3; 32],
            grease: [0x0a0a; 4],
        }
    }

    /// A synthetic ServerHello: TLS 1.2, cipher `c`, optional ALPN, extension 0xff01.
    fn server_hello(cipher: u16, alpn: Option<&str>, version: u16) -> Vec<u8> {
        let mut exts = vec![];
        let mut ext = |kind: u16, data: &[u8]| {
            exts.extend(kind.to_be_bytes());
            exts.extend((data.len() as u16).to_be_bytes());
            exts.extend(data);
        };
        ext(0xff01, &[0]);
        if let Some(a) = alpn {
            let mut body = ((a.len() + 1) as u16).to_be_bytes().to_vec();
            body.push(a.len() as u8);
            body.extend(a.as_bytes());
            ext(0x0010, &body);
        }
        let mut body = version.to_be_bytes().to_vec();
        body.extend([7u8; 32]);
        body.push(0);
        body.extend(cipher.to_be_bytes());
        body.push(0);
        body.extend((exts.len() as u16).to_be_bytes());
        body.extend(exts);
        let mut hs = vec![2];
        hs.extend(&(body.len() as u32).to_be_bytes()[1..]);
        hs.extend(body);
        let mut rec = vec![22, 3, 3];
        rec.extend((hs.len() as u16).to_be_bytes());
        rec.extend(hs);
        rec
    }

